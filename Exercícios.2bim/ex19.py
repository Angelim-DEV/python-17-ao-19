aluno = {
    "nome" : "Carlos",
    "idade" : "17",
    "nome_mae" : "Lucia"
}
#cada item detém uma chave (nome, idade e nome_mae)
# e também um valor (carlos, 17, lucia)

for n in aluno:
    print(n,":",aluno[n])
    # "n" é a chave, "aluno[n]" é o valor dentro da chave
    # "n" é a gaveta (chave), "aluno[n]" aquilo que está dentro da gaveta